    vendor_name VARCHAR(500) NULL DEFAULT NULL COMMENT '供应商名称',
	if_read VARCHAR(20) NULL DEFAULT NULL COMMENT '是否已查阅',
	read_time DATETIME NULL DEFAULT NULL COMMENT '查询时间',
	if_replay VARCHAR(20) NULL DEFAULT NULL COMMENT '是否已回复',
	last_replay_time DATETIME NULL DEFAULT NULL COMMENT '最新回复时间',
	confirm_status VARCHAR(20) NULL DEFAULT NULL COMMENT '确认状态',
	replay_id  BIGINT(20) NULL DEFAULT NULL COMMENT '最新回复id',
	CREATED_ID BIGINT(20) NOT NULL COMMENT '创建人ID',
	CREATED_BY VARCHAR(50) NOT NULL COMMENT '创建人' ,
	CREATION_DATE DATETIME NOT NULL COMMENT '创建时间',
	CREATED_BY_IP VARCHAR(150) NOT NULL COMMENT '创建人IP' ,
	CREATED_FULL_NAME VARCHAR(100) NULL DEFAULT NULL COMMENT '创建人姓名' ,
	LAST_UPDATED_ID BIGINT(20) NULL DEFAULT NULL COMMENT '最后更新人ID',
	LAST_UPDATED_BY VARCHAR(50) NULL DEFAULT NULL COMMENT '更新人' ,
	LAST_UPDATE_DATE DATETIME NULL DEFAULT NULL COMMENT '最后更新时间',
	LAST_UPDATED_BY_IP VARCHAR(150) NULL DEFAULT NULL COMMENT '最后更新人IP' ,
	LAST_UPDATED_FULL_NAME VARCHAR(100) NULL DEFAULT NULL COMMENT '最后更新人姓名' ,
	TENANT_ID VARCHAR(30) NULL DEFAULT NULL COMMENT '租户ID' ,
	VERSION BIGINT(20) NULL DEFAULT '0' COMMENT '版本号',
	PRIMARY KEY (answer_vendor_id) USING BTREE
)
COMMENT='供应商-澄清供应商列表';


