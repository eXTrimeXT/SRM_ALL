CREATE TABLE IF NOT EXISTS scc_npm_sou_answer_vendor (
	answer_vendor_id BIGINT(20) NOT NULL COMMENT '主键ID',
	answer_id BIGINT(20) NOT NULL COMMENT '澄清ID',
	line_num INT(11) NULL DEFAULT NULL COMMENT '序号',
	vendor_id BIGINT(20) NULL DEFAULT NULL COMMENT '供应商ID',
