    `MATERIAL_ID` bigint(20) DEFAULT NULL COMMENT '物料id',
    `MATERIAL_CODE` varchar(100) DEFAULT NULL COMMENT '物料编码',
    `MATERIAL_NAME` varchar(100) DEFAULT NULL COMMENT '物料名称',
    `MATERIAL_DESCRIBE` varchar(500) DEFAULT NULL COMMENT '物料描述',
    `BRAND` varchar(50) DEFAULT NULL COMMENT '品牌',
    `AREA_CODE` varchar(50) DEFAULT NULL COMMENT '区域',
    `CURRENT_MONTH_PRICE` DECIMAL(30,8) DEFAULT NULL COMMENT '当前月份',
    `ONE_PRICE` DECIMAL(30,8) DEFAULT NULL COMMENT '减一最低价',
    `TWO_PRICE` DECIMAL(30,8) DEFAULT NULL COMMENT '减二最低价',
    `THREE_PRICE` DECIMAL(30,8) DEFAULT NULL COMMENT '减三最低价',
    `FOUR_PRICE` DECIMAL(30,8) DEFAULT NULL COMMENT '减四最低价',
    `FIVE_PRICE` DECIMAL(30,8) DEFAULT NULL COMMENT '减五最低价',
    `SIX_PRICE` DECIMAL(30,8) DEFAULT NULL COMMENT '减六最低价',
    `SEVEN_PRICE` DECIMAL(30,8) DEFAULT NULL COMMENT '减七最低价',
    `EIGHT_PRICE` DECIMAL(30,8) DEFAULT NULL COMMENT '减八最低价',
    `NINE_PRICE` DECIMAL(30,8) DEFAULT NULL COMMENT '减九最低价',
