CREATE TABLE IF NOT EXISTS `scc_pj_notice` (
    `NOTICE_ID` bigint(20) NOT NULL COMMENT '主键ID',
    `NOTICE_TYPE` varchar(20) NOT NULL COMMENT '公告分类',
    `NOTICE_STATUS` varchar(20) NOT NULL COMMENT '状态',
    `TITLE` varchar(240) NOT NULL COMMENT '标题',
    `DETAIL` varchar(5000) NOT NULL COMMENT '正文',
    `PUBLISHER_ID` bigint(20) DEFAULT NULL COMMENT '发布人ID',
    `PUBLISH_TIME` datetime DEFAULT NULL COMMENT '发布时间',
    `PUBLISH_BY` varchar(50) DEFAULT NULL COMMENT '发布人名称',
    `FILE_RELATION_ID` bigint(20) DEFAULT NULL COMMENT '附件ID',
    `FILE_NAME` varchar(240) DEFAULT NULL COMMENT '附件名称',
    `IS_TOP` varchar(2) DEFAULT 'N' COMMENT '置顶公告,Y：是,N：否',
    `CREATED_ID` bigint(20) NOT NULL COMMENT '创建人ID',
    `CREATED_BY` varchar(50) NOT NULL COMMENT '创建人',
    `CREATION_DATE` datetime NOT NULL COMMENT '创建时间',
    `CREATED_BY_IP` varchar(150) NOT NULL COMMENT '创建人IP',
    `CREATED_FULL_NAME` varchar(100) DEFAULT NULL COMMENT '创建人姓名',
    `LAST_UPDATED_ID` bigint(20) DEFAULT NULL COMMENT '最后更新人ID',
    `LAST_UPDATED_BY` varchar(50) DEFAULT NULL COMMENT '更新人',
    `LAST_UPDATE_DATE` datetime DEFAULT NULL COMMENT '最后更新时间',
    `LAST_UPDATED_BY_IP` varchar(150) DEFAULT NULL COMMENT '最后更新人IP',
    `LAST_UPDATED_FULL_NAME` varchar(100) DEFAULT NULL COMMENT '最后更新人姓名',
    `TENANT_ID` varchar(30) DEFAULT NULL COMMENT '租户ID',
    `VERSION` bigint(20) DEFAULT '0' COMMENT '版本号',
    `NOTICE_SOURCE` varchar(100) DEFAULT NULL COMMENT '通知来源(说明是根据其他单据来创建的,为空则为手动创建)：BIDING(招标单通知)',
    `SOURCE_FORM_ID` bigint(20) DEFAULT NULL COMMENT '来源单据ID',
    PRIMARY KEY (`NOTICE_ID`) USING BTREE
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='公告表';