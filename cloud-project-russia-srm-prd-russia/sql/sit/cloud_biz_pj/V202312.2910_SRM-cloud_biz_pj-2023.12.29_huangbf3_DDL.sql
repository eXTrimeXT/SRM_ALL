-- 创建BPM审批历史表
CREATE TABLE IF NOT EXISTS `scc_pj_bpm_task_history` (
    `BPM_TASK_HISTORY_ID` bigint(20) NOT NULL COMMENT '主键ID',
    `ORDER_ID` bigint(20) NOT NULL COMMENT '业务单据ID',
    `MSG` varchar(300) DEFAULT NULL COMMENT '备注',
    `PROCESS_INST_ID` varchar(40) DEFAULT NULL COMMENT '流程实例ID',
    `ACTIVITY_NAME` varchar(40) DEFAULT NULL COMMENT '节点处理人',
    `CREATE_DATE` varchar(40) DEFAULT NULL COMMENT '节点处理时间',
    `CREATE_USER_NAME` varchar(40) DEFAULT NULL COMMENT '审批人姓名',
    `CREATE_USER` varchar(40) DEFAULT NULL COMMENT '审批工号',
    `ACTION_NAME` varchar(40) DEFAULT NULL COMMENT '节点处理类型',
    `CREATED_ID` bigint(20) NOT NULL COMMENT '创建人ID',
    `CREATED_BY` varchar(50) NOT NULL COMMENT '创建人',
    `CREATION_DATE` datetime NOT NULL COMMENT '创建时间',
    `CREATED_BY_IP` varchar(150) NOT NULL COMMENT '创建人IP',
    `CREATED_FULL_NAME` varchar(100) NOT NULL COMMENT '创建人姓名',
    `LAST_UPDATED_ID` bigint(20) DEFAULT NULL COMMENT '最后更新人ID',
    `LAST_UPDATED_BY` varchar(50) DEFAULT NULL COMMENT '更新人',
    `LAST_UPDATE_DATE` datetime DEFAULT NULL COMMENT '最后更新时间',
    `LAST_UPDATED_BY_IP` varchar(150) DEFAULT NULL COMMENT '最后更新人IP',
    `LAST_UPDATED_FULL_NAME` varchar(100) DEFAULT NULL COMMENT '最后更新人姓名',
    `TENANT_ID` varchar(30) DEFAULT NULL COMMENT '租户ID',
    `VERSION` bigint(10) DEFAULT NULL COMMENT '版本号',
    PRIMARY KEY (`BPM_TASK_HISTORY_ID`) USING BTREE
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='bpm审批历史';